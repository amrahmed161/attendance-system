export function PreferencesProvider({ children }) {
  const [locale, setLocale] = useState(() => localStorage.getItem('dashboard_locale') || 'en')
  const [theme, setTheme] = useState(() => localStorage.getItem('dashboard_theme') || 'light')

  useEffect(() => {
    const root = document.documentElement
    root.lang = locale
    root.dir = locale === 'ar' ? 'rtl' : 'ltr'
    root.dataset.theme = theme
    localStorage.setItem('dashboard_locale', locale)
    localStorage.setItem('dashboard_theme', theme)
  }, [locale, theme])

  const t = useCallback((key) => messages[locale]?.[key] || key, [locale])

  const value = {
    locale,
    theme,
    t,
    setLocale,
    toggleLocale: () => setLocale((current) => current === 'en' ? 'ar' : 'en'),
    toggleTheme: () => setTheme((current) => current === 'dark' ? 'light' : 'dark'),
  }

  return <PreferencesContext.Provider value={value}>{children}</PreferencesContext.Provider>
}
